const W = 5, H = 5;

/** Render `text` as block-capital rows. */
export function banner(text, block = '█') {
    const chars = text.toUpperCase().split('');
    const rows = [];
    for (let y = 0; y < H; y++) {
        let row = '';
        for (const ch of chars) {
            const g = GLYPHS[ch];
            if (!g) { row += ' '.repeat(W + 1); continue; }
            for (let x = 0; x < W; x++) row += g[y * W + x] === '1' ? block : ' ';
            row += ' ';
        }
        rows.push(row.replace(/\s+$/, ''));
    }
    return rows;
}
